export function buildOpenAIInput(payload, risk) {
  const safety = risk?.level === 'urgent' || risk?.level === 'emergency'
    ? '检测到紧急人身安全风险：停止命理预测，只输出即时求助和现实安全行动。'
    : risk?.level === 'high'
      ? '检测到高风险专业问题：专业现实建议必须覆盖普通宜忌。'
      : '按普通文化辅助解读处理。';
  return [
    { role: 'developer', content: [{ type: 'input_text', text: SYSTEM_PROMPT }] },
    { role: 'user', content: [{ type: 'input_text', text: `${safety}\n以下是完整占问记录，请逐项结合具体问题生成结构化解读：\n${JSON.stringify(payload)}` }] }
  ];
}
